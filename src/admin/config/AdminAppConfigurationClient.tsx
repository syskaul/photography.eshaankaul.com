'use client';

import {
  ComponentProps,
  Fragment,
  JSX,
  ReactNode,
  useEffect,
  useState,
} from 'react';
import ChecklistRow from '@/components/ChecklistRow';
import ChecklistGroup from '@/components/ChecklistGroup';
import { AppConfiguration } from '@/app/config';
import StatusIcon from '@/components/StatusIcon';
import { labelForStorage } from '@/platforms/storage';
import { testConnectionsAction } from '@/admin/actions';
import ErrorNote from '@/components/ErrorNote';
import SecretGenerator from '@/app/SecretGenerator';
import EnvVar from '@/components/EnvVar';
import AdminLink from '@/admin/AdminLink';
import ScoreCardContainer from '@/components/ScoreCardContainer';
import { CATEGORY_KEYS, DEFAULT_CATEGORY_KEYS } from '@/category';
import {
  AI_AUTO_GENERATED_FIELDS_ALL,
  AI_AUTO_GENERATED_FIELDS_DEFAULT,
} from '@/photo/ai';
import Link from 'next/link';
import {
  PATH_FEED_JSON,
  PATH_LIBRARY,
  PATH_RSS_XML,
} from '@/app/path';
import {
  AdminConfigSection,
  ConfigSectionKey,
  getAdminConfigSections,
} from '.';
import { getOrderedKeyListStatus } from '@/utility/key';

export default function AdminAppConfigurationClient({
  // Storage
  hasDatabase,
  isPostgresSslEnabled,
  hasRedisStorage,
  hasStorageProvider,
  hasVercelBlobStorage,
  hasCloudflareR2Storage,
  hasAwsS3Storage,
  hasMinioStorage,
  hasMultipleStorageProviders,
  currentStorage,
  // Auth
  hasAuthSecret,
  hasAdminUser,
  // Performance
  isStaticallyOptimized,
  arePhotosStaticallyOptimized,
  arePhotoOGImagesStaticallyOptimized,
  arePhotoCategoriesStaticallyOptimized,
  arePhotoCategoryOgImagesStaticallyOptimized,
  areOriginalUploadsPreserved,
  hasImageQuality,
  imageQuality,
  isBlurEnabled,
  // AI
  isVercelDeployment,
  hasOpenaiSecretKey,
  hasAiGatewayModel,
  openaiModel,
  aiContentGenerationProvider,
  isAiContentGenerationEnabled,
  aiTextAutoGeneratedFields,
  hasAiTextAutoGeneratedFields,
  // Location
  hasLocationServices,
  // Categories
  hasCategoryVisibility,
  categoryVisibility,
  // Search
  isSearchEnabled,
  // Design
  hasHighDensityPreviews,
  // Settings
  areSiteFeedsEnabled,
  // Analytics
  hasMixpanelToken,
  // Debugging
  isDebuggingEnabled,
  // Internal
  areInternalToolsEnabled,
  areAdminDebugToolsEnabled,
  isAdminSqlDebugEnabled,
  isAdminStorageDebugEnabled,
  // Auth
  secret,
  // Connection status
  databaseError,
  storageError,
  redisError,
  aiError,
  locationError,
  // Component props
  simplifiedView,
  isAnalyzingConfiguration,
}: AppConfiguration &
  { secret: string } &
  Partial<Awaited<ReturnType<typeof testConnectionsAction>>> & {
    simplifiedView?: boolean
    isAnalyzingConfiguration?: boolean
  }) {
  const [hasScrolled, setHasScrolled] = useState(false);

  useEffect(() => {
    const handleScroll = () => { setHasScrolled(true); };
    window.addEventListener('scroll', handleScroll);
    return () => {
      window.removeEventListener('scroll', handleScroll);
    };
  }, []);

  const renderEnvVars = (variables: (string | {
    variable: string,
    optional?: boolean,
    value?: string,
  })[]) =>
    <div className="pt-1 flex flex-col gap-0.5">
      {variables.map(_variable => {
        const { variable, optional, value } = typeof _variable === 'string'
          ? { variable: _variable }
          : _variable;
        return <EnvVar
          key={variable}
          {...{
            variable,
            value,
            ...optional && { trailingContent:
              <span className="text-dim">(optional)</span>,
            },
          }}
        />;
      })}
    </div>;

  const renderSubStatus = (
    type: ComponentProps<typeof StatusIcon>['type'],
    label: ReactNode,
    iconClassName = 'translate-y-[4px]',
  ) =>
    <div className="flex gap-2">
      <StatusIcon {...{ type, className: iconClassName }} />
      <span className="min-w-0">
        {label}
      </span>
    </div>;
    
  const renderSubStatusWithEnvVar = (
    type: ComponentProps<typeof StatusIcon>['type'],
    variable: string,
  ) =>
    renderSubStatus(
      type,
      renderEnvVars([variable]),
      'translate-y-[7px]',
    );

  const renderOrderedKeyList = (
    selectedKeys: string[],
    acceptedKeys: readonly string[],
  ) =>
    <div>
      {getOrderedKeyListStatus({ selectedKeys, acceptedKeys })
        .map(({ label, selected }) =>
          <Fragment key={label}>
            {renderSubStatus(
              selected ? 'checked' : 'optional',
              selected
                ? label
                : <span className="text-dim">{label}</span>,
            )}
          </Fragment>)}
    </div>;

  const renderError = ({
    connection,
    message,
  }: {
    connection?: { provider: string, error: string }
    message?: string
  }) =>
    <ErrorNote className="mt-2 mb-3">
      {connection && <>
        {connection.provider} connection error: {`"${connection.error}"`}
      </>}
      {message}
    </ErrorNote>;

  const renderLink = (
    href: string,
    children?: ReactNode,
    isExternal = true,
  ) =>
    <Link
      href={href}
      className="underline underline-offset-3 hover:no-underline"
      target={isExternal ? '_blank' : undefined}
    >
      {children || href}
    </Link>;

  const renderCommaSeparatedList = (items: string[]) =>
    <>
      {'"'}
      {items.map((item, index) => <Fragment key={index}>
        {item}{index < items.length - 1 ? <>,&#8203;</> : <></>}
      </Fragment>)}
      {'"'}
    </>;

  const renderGroupContent = (key: ConfigSectionKey): JSX.Element => {
    switch (key) {
      case 'Storage':
        return <>
          <ChecklistRow
            title={hasDatabase && isAnalyzingConfiguration
              ? 'Testing database connection'
              : 'Setup database'}
            status={hasDatabase}
            isPending={hasDatabase && isAnalyzingConfiguration}
          >
            {databaseError && renderError({
              connection: { provider: 'Database', error: databaseError},
            })}
            {hasDatabase
              ? renderSubStatus(
                'checked',
                // eslint-disable-next-line @stylistic/max-len
                `Postgres: connected${!isPostgresSslEnabled ? ' (SSL disabled)' : ''}`,
              )
              : renderSubStatus('missing', <>
                Postgres:
                {' '}
                <AdminLink
                  href="https://vercel.com/docs/postgres"
                  externalIcon
                >
                  create database
                </AdminLink>
                {' '}
                and connect to project
              </>)}
          </ChecklistRow>
          <ChecklistRow
            title={
              hasStorageProvider && isAnalyzingConfiguration
                ? 'Testing storage connection'
                : !hasStorageProvider
                  ? 'Setup storage (one of the following)'
                  : hasMultipleStorageProviders
                  // eslint-disable-next-line @stylistic/max-len
                    ? `Setup storage (new uploads go to: ${labelForStorage(currentStorage)})`
                    : 'Setup storage'}
            status={hasStorageProvider}
            isPending={hasStorageProvider && isAnalyzingConfiguration}
          >
            {storageError && renderError({
              connection: { provider: 'Storage', error: storageError},
            })}
            <div>
              {hasVercelBlobStorage
                ? renderSubStatus('checked', 'Vercel Blob: connected')
                : renderSubStatus('optional', <>
                  {labelForStorage('vercel-blob')}:
                  {' '}
                  <AdminLink
                    href="https://vercel.com/docs/vercel-blob"
                    externalIcon
                  >
                    create store
                  </AdminLink>
                  {' '}
                  (configured as public) and connect to project
                </>,
                )}
              {hasCloudflareR2Storage
                ? renderSubStatus('checked', 'Cloudflare R2: connected')
                : renderSubStatus('optional', <>
                  {labelForStorage('cloudflare-r2')}:
                  {' '}
                  <AdminLink
                    href="https://developers.cloudflare.com/r2/buckets/"
                    externalIcon
                  >
                    create/configure bucket
                  </AdminLink>
                </>)}
              {hasAwsS3Storage
                ? renderSubStatus('checked', 'AWS S3: connected')
                : renderSubStatus('optional', <>
                  {labelForStorage('aws-s3')}:
                  {' '}
                  <AdminLink
                  // eslint-disable-next-line @stylistic/max-len
                    href="https://docs.aws.amazon.com/AmazonS3/latest/userguide/create-bucket-overview.html"
                    externalIcon
                  >
                    create/configure bucket
                  </AdminLink>
                </>)}
              {hasMinioStorage
                ? renderSubStatus('checked', 'MinIO: connected')
                : renderSubStatus('optional', <>
                  {labelForStorage('minio')}:
                  {' '}
                  <AdminLink
                  // eslint-disable-next-line @stylistic/max-len
                    href="https://min.io/docs/minio/linux/administration/identity-access-management/policy-based-access-control.html"
                    externalIcon
                  >
                    setup MinIO server
                  </AdminLink>
                </>)}
            </div>
          </ChecklistRow>
        </>;
      case 'Authentication':
        return <>
          <ChecklistRow
            title={!hasAuthSecret && isAnalyzingConfiguration
              ? 'Generating secret'
              : 'Setup auth'}
            status={hasAuthSecret}
            isPending={!hasAuthSecret && isAnalyzingConfiguration}
          >
            Store auth secret in environment variable
            {!hasAuthSecret &&
            <div className="overflow-x-auto">
              <SecretGenerator {...{ secret }} />
            </div>}
            {renderEnvVars(['AUTH_SECRET'])}
          </ChecklistRow>
          <ChecklistRow
            title="Setup admin user"
            status={hasAdminUser}
          >
            Store admin email/password
            {' '}
            in environment variables
            {renderEnvVars([
              'ADMIN_EMAIL',
              'ADMIN_PASSWORD',
            ])}
          </ChecklistRow>
        </>;
      case 'External Services':
        return <>
          <ChecklistRow
            title={hasRedisStorage && isAnalyzingConfiguration
              ? 'Testing Redis connection'
              : 'Rate limiting'}
            status={hasRedisStorage}
            isPending={hasRedisStorage && isAnalyzingConfiguration}
            showWarning={isAiContentGenerationEnabled || hasLocationServices}
            optional
          >
            {redisError && renderError({
              connection: { provider: 'Redis', error: redisError},
            })}
            Create Upstash Redis store from storage tab
            on Vercel dashboard and connect to this project
            to enable rate limiting on external services
          </ChecklistRow>
          <ChecklistRow
            title={aiContentGenerationProvider === 'gateway'
              && isAnalyzingConfiguration
              ? 'Testing AI Gateway connection'
              : 'AI (Gateway)'}
            status={aiContentGenerationProvider === 'gateway'}
            showWarning={hasAiGatewayModel
              && aiContentGenerationProvider !== 'gateway'}
            isPending={aiContentGenerationProvider === 'gateway'
              && isAnalyzingConfiguration}
            optional
          >
            {aiError
              && aiContentGenerationProvider === 'gateway'
              && renderError({
                connection: { provider: 'AI Gateway', error: aiError},
              })}
            Store creator/model ({'"openai/gpt-5.2"'}) to use the
            {' '}
            {renderLink(
              'https://vercel.com/docs/ai-gateway',
              'Vercel AI Gateway',
            )}
            {' '}
            to enable AI-generated titles, captions, and semantic descriptions.
            The invisible semantic description supports
            {' '}
            CMD-K search and image accessibility.
            {' '}
            API key only necessary for non-Vercel deployments.
            {renderEnvVars(isVercelDeployment
              ? ['AI_GATEWAY_MODEL']
              : ['AI_GATEWAY_MODEL', 'AI_GATEWAY_API_KEY'])}
          </ChecklistRow>
          <ChecklistRow
            title={hasOpenaiSecretKey && isAnalyzingConfiguration
              ? 'Testing OpenAI connection'
              : 'AI (legacy OpenAI)'}
            status={hasOpenaiSecretKey}
            isPending={hasOpenaiSecretKey && isAnalyzingConfiguration}
            optional
          >
            {aiError
              && aiContentGenerationProvider === 'openai'
              && renderError({
                connection: { provider: 'OpenAI', error: aiError},
              })}
            Takes precedence over AI Gateway when configured.
            Optionally override the model
            {' '}
            {'(set OPENAI_MODEL to \'compatible\' to use gpt-4o)'}
            {' '}
            or base URL for OpenAI-compatible providers.
            {renderEnvVars([
              { variable: 'OPENAI_SECRET_KEY' },
              { variable: 'OPENAI_MODEL', optional: true, value: openaiModel },
              { variable: 'OPENAI_BASE_URL', optional: true },
            ])}
          </ChecklistRow>
          <ChecklistRow
            title={hasLocationServices && isAnalyzingConfiguration
              ? 'Testing Google Places/Geocoding connection'
              : 'Google Places/Geocoding'}
            status={hasLocationServices}
            isPending={hasLocationServices && isAnalyzingConfiguration}
            optional
          >
            {locationError && renderError({
              connection: {
                provider: 'Google Places/Geocoding',
                error: locationError,
              },
            })}
            Store Google Places/Geocoding API key to add location meta
            to entities like photos and albums
            {renderEnvVars(['GOOGLE_PLACES_GEOCODING_API_KEY'])}
          </ChecklistRow>
        </>;
      case 'AI Text':
        return <>
          <ChecklistRow
            title={'Auto-generated text fields'}
            status={
              hasAiTextAutoGeneratedFields &&
              isAiContentGenerationEnabled}
            showWarning={hasAiTextAutoGeneratedFields
              && !isAiContentGenerationEnabled}
            optional
          >
            <div>
              {hasAiTextAutoGeneratedFields &&
              AI_AUTO_GENERATED_FIELDS_ALL.map(field =>
                <Fragment key={field}>
                  {renderSubStatus(
                    aiTextAutoGeneratedFields.includes(field)
                      ? 'checked'
                      : 'optional',
                    field,
                  )}
                </Fragment>)}
            </div>
            {!isAiContentGenerationEnabled && <>
              No provider configured above — these
              fields will not be generated until one is set up.
              {' '}
            </>}
            Comma-separated fields to auto-generate when
            uploading photos. Accepted values: title, caption,
            semantic, all, or none
            {' '}
            (default: {renderCommaSeparatedList(
              AI_AUTO_GENERATED_FIELDS_DEFAULT,
            )})
            {renderEnvVars(['AI_TEXT_AUTO_GENERATED_FIELDS'])}
          </ChecklistRow>
        </>;
      case 'Performance':
        return <>
          <ChecklistRow
            title="Static optimization"
            status={isStaticallyOptimized}
            optional
          >
            Set environment variable to {'"1"'} to make site more responsive
            by enabling static optimization
            (i.e., rendering pages and images at build time)
            <div>
              {renderSubStatusWithEnvVar(
                arePhotosStaticallyOptimized ? 'checked' : 'optional',
                'NEXT_PUBLIC_STATICALLY_OPTIMIZE_PHOTOS',
              )}
              {renderSubStatusWithEnvVar(
                arePhotoOGImagesStaticallyOptimized ? 'checked' : 'optional',
                'NEXT_PUBLIC_STATICALLY_OPTIMIZE_PHOTO_OG_IMAGES',
              )}
              {renderSubStatusWithEnvVar(
                arePhotoCategoriesStaticallyOptimized ? 'checked' : 'optional',
                'NEXT_PUBLIC_STATICALLY_OPTIMIZE_PHOTO_CATEGORIES',
              )}
              {renderSubStatusWithEnvVar(
              // eslint-disable-next-line @stylistic/max-len
                arePhotoCategoryOgImagesStaticallyOptimized ? 'checked' : 'optional',
                'NEXT_PUBLIC_STATICALLY_OPTIMIZE_PHOTO_CATEGORY_OG_IMAGES',
              )}
            </div>
          </ChecklistRow>
          <ChecklistRow
            title="Preserve original uploads"
            status={areOriginalUploadsPreserved}
            optional
          >
            Set environment variable to {'"1"'} to prevent
            image uploads being compressed before storing
            {renderEnvVars(['NEXT_PUBLIC_PRESERVE_ORIGINAL_UPLOADS'])}
          </ChecklistRow>
          <ChecklistRow
            title={`Image quality: ${imageQuality}`}
            status={hasImageQuality}
            optional
          >
            Set environment variable from {'"1-100"'}
            {' '}
            to control the quality of large photos
            ({'"100"'} represents highest quality/largest size)
            {renderEnvVars(['NEXT_PUBLIC_IMAGE_QUALITY'])}
          </ChecklistRow>
          <ChecklistRow
            title="Image blur"
            status={isBlurEnabled}
            optional
          >
            Set environment variable to {'"1"'} to prevent
            image blur data being stored and displayed
            {renderEnvVars(['NEXT_PUBLIC_DISABLE_BLUR'])}
          </ChecklistRow> 
        </>;
      case 'Categories':
        return <>
          <ChecklistRow
            title="Visibility and ordering"
            status={hasCategoryVisibility}
            optional
          >
            {renderOrderedKeyList(categoryVisibility, CATEGORY_KEYS)}
            <div>
              Configure order and visibility of categories
              (seen in grid sidebar and CMD-K results)
              by storing comma-separated values
              (default: {renderCommaSeparatedList(DEFAULT_CATEGORY_KEYS)})
            </div>
            {renderEnvVars(['NEXT_PUBLIC_CATEGORY_VISIBILITY'])}
          </ChecklistRow>
          <ChecklistRow
            title="Search"
            status={isSearchEnabled}
            optional
          >
            Set environment variable to {'"1"'} to enable search
            (nav button, CMD-K, and editable query headers)
            {renderEnvVars(['NEXT_PUBLIC_ENABLE_SEARCH'])}
          </ChecklistRow>
        </>;
      case 'Design':
        return <>
          <ChecklistRow
            title="Tinted folders"
            status={true}
          >
            Folder tinting is always enabled on {renderLink(PATH_LIBRARY)}.
          </ChecklistRow>
          <ChecklistRow
            title="High density previews"
            status={hasHighDensityPreviews}
            optional
          >
            Set environment variable to {'"1"'} to show up to 6 photos
            in OG images (defaults to 5)
            {renderEnvVars(['NEXT_PUBLIC_HIGH_DENSITY_PREVIEWS'])}
          </ChecklistRow>
        </>;
      case 'Settings':
        return <>
          <ChecklistRow
            title="Site feeds (JSON/RSS)"
            status={areSiteFeedsEnabled}
            optional
          >
            Set environment variable to {'"1"'} to enable
            {' '}
            {renderLink(PATH_FEED_JSON)} and {renderLink(PATH_RSS_XML)}
            {' '}
            feeds
            {renderEnvVars(['NEXT_PUBLIC_SITE_FEEDS'])}
          </ChecklistRow>
        </>;
      case 'Analytics':
        return <>
          <ChecklistRow
            title="Mixpanel"
            status={hasMixpanelToken}
            optional
          >
            Set the Mixpanel project token below. Tracking is skipped in
            regions where consent would be required.
            {renderEnvVars(['NEXT_PUBLIC_MIXPANEL_TOKEN'])}
          </ChecklistRow>
        </>;
      case 'Debugging':
        return <>
          <ChecklistRow
            title="Debug outputs"
            status={isDebuggingEnabled}
            optional
          >
            Set environment variable to {'"1"'} to disable build identifiers
            and other debug outputs.
            {renderEnvVars(['DISABLE_DEBUG_OUTPUTS'])}
          </ChecklistRow>
        </>;
      case 'Internal':
        return <>
          <ChecklistRow
            title="Debug tools"
            status={areAdminDebugToolsEnabled}
            optional
          >
            Set environment variable to {'"1"'} to temporarily enable
            diagnostic tools like the baseline grid and image fallbacks.
            {renderEnvVars(['ADMIN_DEBUG_TOOLS'])}
          </ChecklistRow>
          <ChecklistRow
            title="SQL debugging"
            status={isAdminSqlDebugEnabled}
            optional
          >
            Set environment variable to {'"1"'} to enable
            console output for all sql queries
            {renderEnvVars(['ADMIN_SQL_DEBUG'])}
          </ChecklistRow>
          <ChecklistRow
            title="Storage debugging"
            status={isAdminStorageDebugEnabled}
            optional
          >
            Set environment variable to {'"1"'} to enable
            storage debugging
            {renderEnvVars(['ADMIN_STORAGE_DEBUG'])}
          </ChecklistRow>
        </>;
    }
  };

  return (
    <ScoreCardContainer>
      {getAdminConfigSections(areInternalToolsEnabled, simplifiedView)
        .map((section) => (
          <ChecklistGroup
            key={section.title}
            title={section.title}
            titleShort={(section as AdminConfigSection).titleShort}
            icon={section.icon}
            optional={!section.required}
            updateHashOnVisible={hasScrolled && !simplifiedView}
          >
            {renderGroupContent(section.title)}
          </ChecklistGroup>
        ))}
      <div className="pl-11 pr-2 sm:pr-11 mt-4 md:mt-7">
        <div>
          Changes to environment variables require a new deployment
          to take effect
        </div>
      </div>
    </ScoreCardContainer>
  );
}
